        <section class="block">
          <div class="prose">
            <h2>Where</h2>
            <p>The Old Library, 3 Wrenbury Street, Bristol BS6 5QT. The entrance
              is the arched door on Wrenbury Street itself. Old Library Yoga is the room
              at the back, straight through the central hall.</p>
            <p><a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a><br>
               <a href="tel:+441174960231">+44 117 496 0231</a></p>

            <h2>Access</h2>
            <p>Step-free from the street to the studio: there is a ramp at the
              front door and the studio is on the ground floor, with no steps
              anywhere on the route. The toilet is on the same level, is
              accessible, and has a baby changing mat and a bin.</p>
            <p>Prams come inside and go along the back wall of the studio rather
              than in the corridor. There is room for six.</p>
            <p>Chairs are available in every class and a chair-based version of
              the whole prenatal class exists and has been taught many times. If
              you are not sure whether the room will work for you, email and
              describe the situation rather than guessing from this page.</p>

            <h2>Getting here</h2>
            <p>Ten minutes' walk from Gloucester Road. The 70, 72 and 73 stop on
              Cheltenham Road, four minutes away. There is free two-hour
              on-street parking on Wrenbury Street and the surrounding roads,
              which covers any class.</p>

            <h2>Booking and cancelling</h2>
            <p>Email and say which class. You will get a reply confirming it.
              Pay at the studio by card or bank transfer &mdash; there is nothing
              to set up in advance and no card details are held.</p>
            <p>Cancel at any time before the class starts, for any reason or no
              reason, and it is not charged. This is deliberate: the people in
              these classes are regularly sick, exhausted, at a scan that
              overran, or simply unable to face it, and a twenty-four-hour
              cancellation policy would be a policy designed for a different
              kind of customer.</p>

            <h2>When you will hear back</h2>
            <p>Within a day on weekdays and within three at the outside. If you
              have not heard in three days the email has gone astray, which
              happens occasionally with the contact form, and the thing to do is
              ring the number above and leave a message.</p>
            <p>There is no automated reply, no ticket number and no chatbot. The
              reply you get will be from Anwen, will answer the question you
              actually asked, and will tell you plainly if the answer is that
              you should speak to your midwife instead.</p>

            <h2>Things worth telling us</h2>
            <p>How many weeks you are, or how long ago you gave birth. Anything
              a midwife, GP, obstetrician or physiotherapist has said about
              exercise. Pelvic girdle pain, a previous caesarean, a previous
              difficult birth, twins, or a pregnancy that anybody has described
              as high-risk. None of these stops you coming and all of them
              change what you will be offered in the room.</p>
          </div>

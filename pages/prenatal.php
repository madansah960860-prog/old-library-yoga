            <h2>What a class contains</h2>
            <p>The shape is the same every week, which matters more than
              variety when you are tired. Ten minutes sitting and breathing;
              twenty minutes of gentle movement on all fours and seated, mostly
              for the back and pelvis; twenty-five minutes of standing work with
              a wall or a chair nearby; ten minutes of specific preparation
              &mdash; pelvic floor, or breath for labour, or positions; and ten
              minutes of supported rest on your left side under a blanket.</p>
            <p>Nobody is at the front doing a demonstration you are supposed to
              match. Anwen shows a shape, then walks. If four people in the room
              are at thirty-five weeks and two are at fourteen, the class tilts
              towards the thirty-five weeks and the two are given something
              else, out loud, without any fuss.</p>

            <h2>When to start</h2>
            <p>Most people arrive between twelve and sixteen weeks, once the
              first scan is done and the worst of the nausea has passed. That is
              convention rather than a rule. If you practised regularly before
              you were pregnant, you can come earlier. If you are thirty-eight
              weeks and have never done this before, you can come this week
              &mdash; the third-trimester content is the most useful part
              anyway.</p>
            <p>The one thing we ask is that you have had your booking
              appointment with a midwife, and that if anything about your
              pregnancy has been described as high-risk you tell us what you
              were told.</p>

            <h2>What it actually helps with</h2>
            <p>Being specific here matters, because prenatal yoga is sold with a
              great deal of nonsense attached to it.</p>
            <p>It reliably helps with: backache, the specific misery of a pelvis
              that aches by four in the afternoon, sleep, breathlessness as the
              ribs move, and the general business of being in a body that is
              changing weekly. It gives you a long exhale you can use in labour,
              and positions that are genuinely useful when contractions start.
              It puts you in a room with eight other people at the same stage,
              which for a lot of people turns out to be the main thing.</p>
            <p>It does not guarantee a shorter labour, a vaginal birth, an
              easier recovery or a calmer baby. Anyone who tells you otherwise
              is selling something. Birth is not a test you can revise for, and
              a class that implies it is sets people up to feel they failed at
              it.</p>

            <h2>Bring a question</h2>
            <p>The last five minutes are kept for questions, out loud, to the
              room. People ask about heartburn, about whether the baby has
              turned, about what a sweep is, about whether it is normal to feel
              nothing at all about any of it. Anwen answers what a yoga teacher
              can answer and says &ldquo;ask your midwife&rdquo; to the rest,
              which is often.</p>

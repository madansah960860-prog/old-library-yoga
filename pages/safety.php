        <section class="block">
          <div class="head"><h2>Stop, and get advice</h2></div>
          <section class="safety">
            <h3>Stop immediately and contact your midwife or maternity unit</h3>
            <p class="safety__when">Any of these, at any point in pregnancy</p>
            <ul>
              <li>Vaginal bleeding, or any fluid loss.</li>
              <li>Regular painful contractions before 37 weeks.</li>
              <li>Chest pain, palpitations, or breathlessness before you have
                exerted yourself.</li>
              <li>Dizziness, faintness or a headache that will not shift.</li>
              <li>Calf pain or swelling on one side only.</li>
              <li>Reduced or changed fetal movements.</li>
              <li>Sudden swelling of the face, hands or feet, or visual
                disturbance &mdash; these can indicate pre-eclampsia and are
                urgent.</li>
            </ul>
            <p class="safety__note">None of these is a yoga problem and none of
              them should be discussed with a yoga teacher first. Ring your
              maternity triage line. They would far rather hear from you
              unnecessarily.</p>
          </section>
        </section>

        <section class="block">
          <div class="head"><h2>After birth</h2></div>
          <section class="safety">
            <h3>When to come back</h3>
            <p class="safety__when">And what to do first</p>
            <ul>
              <li>After an uncomplicated vaginal birth: from six weeks, after
                your postnatal check.</li>
              <li>After a caesarean: usually ten to twelve weeks, and only once
                your scar is comfortable and you have been checked.</li>
              <li>After a birth involving significant tearing, a repair, or any
                complication: ask your GP or a pelvic health physiotherapist
                specifically, and tell us what they said.</li>
              <li>Whenever you come back, the first block of work is breath,
                pelvic floor and reconnecting the deep abdominals. Not
                &ldquo;getting back into it&rdquo;.</li>
            </ul>
            <p class="safety__note">Breastfeeding does not change what is safe
              in a class, but relaxin can stay in your system for months, and
              longer if you are feeding. Your joints are not as stable as they
              feel.</p>
          </section>
          <section class="safety">
            <h3>Diastasis recti</h3>
            <p class="safety__when">Abdominal separation &mdash; extremely
              common and usually improvable</p>
            <ul>
              <li>Some separation of the abdominal muscles happens in almost
                every pregnancy. It is not an injury and it is not your
                fault.</li>
              <li>Check it yourself: lying on your back, knees bent, lift your
                head and feel along the midline above and below the navel for a
                gap and, more importantly, for how much tension there is across
                it.</li>
              <li>Avoid, for now: sit-ups, crunches, full planks, and getting
                out of bed by sitting straight up. Roll to your side first.</li>
              <li>Do: breath-led deep abdominal work, side-lying work, and
                anything that teaches the abdominal wall to generate tension
                without doming.</li>
              <li>A gap wider than two fingers at three months post-birth is
                worth seeing a pelvic health physiotherapist about. In England
                you can refer yourself in most areas.</li>
            </ul>
            <p class="safety__note">We check for doming in every postnatal
              class and will quietly change what you are doing if we see it.
              That is not a criticism; it is the single most useful thing a
              postnatal teacher does.</p>
          </section>
          <section class="safety">
            <h3>Pelvic girdle pain</h3>
            <p class="safety__when">Pain at the front or back of the pelvis,
              often worse on stairs</p>
            <ul>
              <li>Keep your knees together getting in and out of the car and
                in and out of bed.</li>
              <li>Avoid wide-legged standing postures, deep squats and anything
                that stretches the inner thigh.</li>
              <li>Stay symmetrical: stand on both feet, do not carry a toddler
                on one hip, avoid stairs where you reasonably can.</li>
              <li>Ask to be referred to a women's health physiotherapist. It is
                treatable, and it is not something to endure until birth.</li>
            </ul>
            <p class="safety__note">Tell us if you have this. It changes at
              least half the class for you, and we would rather give you a
              different version of every standing posture than watch you make
              it worse politely.</p>
          </section>
        </section>

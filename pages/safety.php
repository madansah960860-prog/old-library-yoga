        <section class="block">
          <h1>Safety guidance</h1>
          <p class="lede">What is safe, what to change and what to skip, by
            trimester and after birth. Published in full, because guidance you
            can only get by attending is not guidance.</p>
          <div class="prose">
            <p>Everything on this page is general information for an
              uncomplicated pregnancy. It is written by a teacher, not a
              clinician. Where it conflicts with advice from your midwife, GP,
              obstetrician or physiotherapist, follow them &mdash; they have
              examined you and we have not.</p>
          </div>
        </section>

        <section class="block">
          <div class="head"><h2>By trimester</h2></div>
        <section class="safety">
          <h3>First trimester</h3>
          <p class="safety__when">Weeks 1&ndash;13</p>
          <h4>Safe, and worth doing</h4>
          <ul><li>Carrying on with whatever you already did, at a lower intensity. If you practised before you were pregnant, you do not have to stop.</li><li>Standing postures, with a wider stance than usual.</li><li>Open twists &mdash; turning away from the front leg, chest opening out.</li><li>Breathing practice and long rest. Most people need far more of both than they expect in these weeks.</li><li>Resting whenever you want to. Lying down for half the class is a complete and legitimate practice.</li></ul>
          <h4>Skip, or change</h4>
          <ul><li>Starting anything new and strenuous. This is not the term to take up power yoga.</li><li>Hot rooms, saunas and anything that raises your core temperature.</li><li>Deep closed twists that compress the abdomen.</li><li>Breath retention of any kind, and forceful breathing such as kapalabhati.</li><li>Inversions, unless you were already confident in them and feel entirely well.</li></ul>
          <p class="safety__note">The honest summary of the first trimester is that most people do less, not more. Nausea and exhaustion are at their worst before anybody can see you are pregnant, which is a particularly unfair arrangement. Coming to class and lying under a blanket for an hour counts.</p>
        </section>
        <section class="safety">
          <h3>Second trimester</h3>
          <p class="safety__when">Weeks 14&ndash;27</p>
          <h4>Safe, and worth doing</h4>
          <ul><li>Standing postures with a wide base &mdash; these usually feel better now than at any other point.</li><li>Supported gentle backbends over a bolster, which help the ribs as they move.</li><li>Hip work with the knees supported on blocks.</li><li>Pelvic floor work, both the lifting and &mdash; just as important &mdash; the letting go.</li><li>Side-lying rest with a bolster between the knees.</li></ul>
          <h4>Skip, or change</h4>
          <ul><li>Lying flat on your back for longer than a few minutes, from around week 16&ndash;20. Roll to your left side or prop your chest up instead.</li><li>Lying on your front, once it is no longer comfortable &mdash; which is your call, not ours.</li><li>Deep closed twists, and any strong abdominal work including full sit-ups and boat pose.</li><li>Going to your end range in a stretch. Relaxin makes you feel more flexible than your joints can safely support.</li><li>Jumping between postures.</li></ul>
          <p class="safety__note">The middle trimester is when most people feel best and when most people overdo it. The specific trap is relaxin: the hormone loosens ligaments, your range increases, and it feels like progress. It is not progress and chasing it is the most common way to end up with pelvic girdle pain.</p>
        </section>
        <section class="safety">
          <h3>Third trimester</h3>
          <p class="safety__when">Weeks 28 to birth</p>
          <h4>Safe, and worth doing</h4>
          <ul><li>Wide-legged standing postures and supported squats, holding a wall or a chair.</li><li>Supported side-lying rest, which by now is often the only comfortable position.</li><li>Pelvic tilts on all fours &mdash; the single most useful thing for a back that aches by four o'clock.</li><li>Breath practice for labour: the long exhale, and the low-pitched sound that goes with it.</li><li>Positions that help the baby into a good position: forward-leaning inversions, kneeling over a ball, staying off the sofa.</li></ul>
          <h4>Skip, or change</h4>
          <ul><li>Lying flat on your back at all.</li><li>Deep squats if your baby is breech, if you have been told the head is not engaged, or if a midwife has advised against them.</li><li>Balancing without a wall or a chair within reach.</li><li>Anything that involves getting up quickly.</li><li>Stretching the inner thighs hard, particularly if you have any pelvic girdle pain.</li></ul>
          <p class="safety__note">This is the term in which the class stops being about exercise and starts being about preparation: positions, breath, and the specific business of staying comfortable for another eight weeks. It is also the term in which people most often stop coming, usually because they assume they should. You should not; this is when it helps most.</p>
        </section>
        </section>


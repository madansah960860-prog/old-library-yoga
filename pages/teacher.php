            <h2>Training</h2>
            <p>Anwen qualified as a general yoga teacher in Cardiff in 2014
              (200 hours) and specialised almost immediately: 85 hours of
              pregnancy-specific training in 2015, a further 60 hours in
              postnatal practice in 2016, and a 40-hour certificate in
              teaching around pelvic girdle pain and diastasis recti in
              2019.</p>
            <p>She holds a current DBS check, paediatric and adult first aid,
              and full teaching insurance, and she is happy to show any of them
              to anybody who asks. She does around forty hours of continuing
              study a year, currently mostly in pelvic health, and she is
              straightforward about the fact that some of what she was taught in
              2015 &mdash; particularly about what pregnant people should not do
              &mdash; has turned out to be overcautious and is no longer taught
              here.</p>

            <h2>Before this</h2>
            <p>Nine years as a secondary school science teacher, which she says
              is the single most useful preparation for standing in front of
              twelve people and explaining a pelvic floor without anybody dying
              of embarrassment.</p>
            <p>She came to prenatal yoga as a student in 2012, during her first
              pregnancy, at a class she describes as &ldquo;well-meant and
              almost entirely useless&rdquo; &mdash; forty minutes of breathing
              and a long silence where the practical information should have
              been. Old Library Yoga is, fairly explicitly, the class she wanted and did
              not get.</p>

            <h2>How she teaches</h2>
            <p>Plainly, and with the anatomy included. Anwen's view is that the
              main problem with pregnancy yoga is not that it is unsafe but that
              it is vague: people are told to listen to their bodies without
              being told what they are listening for. So classes here name
              things &mdash; the round ligament, the pelvic floor, relaxin,
              supine hypotension &mdash; and explain why an instruction exists
              rather than simply issuing it.</p>
            <p>She does not adjust anybody with her hands without asking first,
              every time, and in a pregnancy class she asks before each
              individual adjustment rather than once at the start.</p>

            <h2>Cover, and what happens if she is ill</h2>
            <p>There is no second teacher, so a class Anwen cannot teach is a
              class that does not happen. Everybody booked in is emailed, and
              cancelled classes are never taken off a five-class card. In the
              six years Old Library Yoga has been running this has happened eleven
              times.</p>
            <p>The alternative &mdash; keeping a list of cover teachers who do
              not know the room or the people in it &mdash; is worse. In a
              pregnancy class the teacher needs to know who is thirty-six weeks,
              who has pelvic girdle pain and who had a difficult birth last
              time, and a stranger with a register cannot know any of it.</p>

            <h2>What she will not tell you</h2>
            <p>That yoga will give you a better birth. That your baby will be
              calmer. That breathing correctly will mean you do not need pain
              relief. That any of this is a substitute for a midwife.</p>
            <p>She is also careful about the word &ldquo;natural&rdquo;. A
              caesarean, an epidural and an induction are all perfectly good
              ways for a person to be born, and a prenatal class that implies
              otherwise does real harm to people who then have one.</p>

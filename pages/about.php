            <h2>The building</h2>
            <p>The Old Library on Wrenbury Street was built in 1893 and lent
              books to this part of Bristol until 1988. It spent twenty years as
              a carpet showroom and is now four workspaces around a central
              hall. Old Library Yoga has the back room, which was the reference library
              and still has the original tall windows along the north wall.</p>
            <p>Those windows are the reason we took it. A room for this kind of
              teaching needs even, soft, indirect light all day and no point at
              which somebody lying on their left side is looking into the sun.
              It holds twelve mats with proper space between them, which is
              fewer than the floor area suggests and deliberate.</p>

            <h2>Who runs it</h2>
            <p>Anwen Pryce owns and teaches the whole thing. There is no second
              teacher, no receptionist and no manager; if you email, she
              answers, and if a class is cancelled it is because she is ill.
              There is more about her training and how she teaches on the
              <a href="teacher.php">teacher page</a>.</p>

            <h2>Why only pregnancy</h2>
            <p>Because a general studio with a prenatal class on Tuesdays is a
              different product from a studio that only does this, and the
              difference shows in the details. Here, every bolster is already in
              the right place. Every person in the room is in the same
              situation. The teacher has seen four hundred pregnancies rather
              than forty. Nobody has to be the one pregnant person in a room of
              twenty-two-year-olds doing crow pose.</p>
            <p>It is a smaller business than a general studio would be and it
              will stay that way. There is no plan to add a vinyasa class, a
              second location or a teacher training course.</p>

            <h2>What we publish</h2>
            <p>The safety guidance on this site is the same guidance we give in
              the room, written out in full and free to read. Several people
              have asked why we give away the thing people would otherwise pay
              to hear. The answer is that information about what is safe in
              pregnancy should not be behind a class fee, and that the people
              most likely to be hurt by bad advice are exactly the people who
              cannot get to a class in Bristol on a Tuesday morning.</p>
            <p>The site carries display advertising, which pays for the site and
              nothing else. No advertiser sees anything before it is published
              and none has any say in what the guidance says. That is set out on
              the <a href="../policies/advertising-disclosure.php">advertising
              disclosure</a> page.</p>

            <h2>Free places</h2>
            <p>Two places in every class are free, held for anybody who cannot
              pay. There is no application, no evidence required and no
              assessment: you email and say you would like one. They are used
              every week, they have been since 2019, and they are the reason the
              drop-in price is fifteen pounds rather than twelve.</p>

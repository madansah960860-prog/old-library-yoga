            <h2>What we do first</h2>
            <p>Breath, pelvic floor, and reconnecting the deep abdominal wall.
              For most people that is the substance of the first four to six
              weeks of coming back, and it looks like almost nothing from the
              outside: lying down, breathing, and generating a small amount of
              tension across the middle of the body on an exhale.</p>
            <p>It is unglamorous and it is the entire foundation. The abdominal
              wall and the pelvic floor work together, they have both been
              through something considerable, and loading them before they are
              talking to each other again is how people end up with a
              longer-term problem than the one they started with.</p>

            <h2>What we do not do</h2>
            <p>No crunches, no sit-ups, no full planks, no &ldquo;bouncing
              back&rdquo;, and no reference at all to what your body looked like
              before. That last one is a policy rather than a preference. This
              is a room in which nobody will comment on your shape, and that
              turns out to be rarer and more valuable than it should be.</p>
            <p>We also do not do high-impact work, and we will keep not doing it
              for longer than you would like. Running, jumping and anything that
              involves both feet leaving the floor is generally a three-to-six
              month conversation, and it should be had with a pelvic health
              physiotherapist rather than a yoga teacher.</p>

            <h2>Checking for doming</h2>
            <p>In every class Anwen watches the midline of the abdomen for
              doming &mdash; a ridge that appears along the centre when the
              abdominal wall cannot manage the load it is being given. If she
              sees it, she will change what you are doing. It is not a
              criticism and it does not mean anything has gone wrong; it means
              the exercise is currently too much, and the correction is
              straightforward.</p>
            <p>There is more detail about diastasis recti, including how to
              check it yourself, on the <a href="safety.php">safety page</a>.
              Abdominal separation happens in almost every pregnancy, it is not
              a failure, and in most cases it improves considerably with the
              right work.</p>

            <h2>Coming back at all</h2>
            <p>People arrive at this class between six weeks and three years
              after giving birth, and the later ones are usually apologetic
              about it. There is nothing to apologise for and no window that
              closes. A pelvic floor responds to sensible work at eighteen
              months exactly as it does at eight weeks.</p>
            <p>Babies are not in this class &mdash; that is Friday's class
              instead &mdash; but if childcare falls through and you turn up
              with one, come in. Nobody will mind and it will not be the first
              time.</p>

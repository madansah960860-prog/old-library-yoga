            <h2>Before you come</h2>
            <p>Have had your postnatal check. Tell us in an email what kind of
              birth you had, whether there was any tearing or repair, whether it
              was a caesarean, and anything a midwife, GP or physiotherapist has
              said about returning to exercise. None of that is nosiness: it
              changes what you will be given to do in your first month.</p>
            <p>If you are still bleeding, if your scar is painful, or if you
              have any leaking, heaviness or dragging sensation in the pelvis,
              tell us that too. The last of those is a reason to see a pelvic
              health physiotherapist, and in most parts of England you can refer
              yourself without going through a GP.</p>

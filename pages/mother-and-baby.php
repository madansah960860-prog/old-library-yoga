            <h2>How it works</h2>
            <p>Forty-five minutes rather than sixty, because that is
              realistically the length of a window you have. You bring the baby,
              you put them on a blanket next to your mat or keep them on you,
              and the class runs around them.</p>
            <p>Feeding during the class is normal. Changing a nappy at the back
              is normal. Walking a crying baby up and down the side of the room
              for twenty minutes and doing none of the yoga at all is normal,
              and it is still worth having come. Roughly half of any given class
              is doing something other than the thing being taught at any
              moment, and the class is designed around that rather than
              tolerating it.</p>

            <h2>What the yoga actually is</h2>
            <p>Shoulders, upper back and neck, mostly &mdash; the specific
              damage done by feeding, carrying and looking down at a small
              person for eleven hours a day. Some standing work, some floor
              work, a lot of chest opening, and pelvic floor work that continues
              from the postnatal class.</p>
            <p>There is also a short section each week where the baby is
              involved rather than parked: simple movement with them, and some
              baby massage strokes for the legs and stomach which are genuinely
              useful for wind and are taught properly rather than as a
              novelty.</p>

            <h2>Ages</h2>
            <p>From six weeks, or from whenever you have been cleared to
              exercise, until crawling. Once a baby is properly mobile the class
              stops working &mdash; for you and for everybody else &mdash; and
              at that point people usually move to the Wednesday postnatal class
              and find childcare for an hour. Nobody is asked to leave; it
              becomes obvious.</p>

            <h2>The other half of it</h2>
            <p>It is worth saying plainly that for a lot of people the yoga is
              the second reason they come. The first is being in a warm room at
              one o'clock on a Friday with seven other adults who are also
              seven weeks in, also not sleeping, and also unsure whether any of
              this is normal.</p>
            <p>We leave twenty minutes at the end with the kettle on. Nobody is
              obliged to stay and plenty of people do not, but the class was
              designed with that twenty minutes in it rather than as an
              afterthought.</p>

            <h2>Practical</h2>
            <p>&pound;11 a class, no card needed. Bring a blanket for the baby,
              a spare nappy and whatever you feed with. Everything else is here.
              There is a lift, there is room for prams inside rather than in the
              corridor, and there is a changing mat and a bin in the toilet.</p>
            <p>The room is kept at twenty-two degrees, which is warmer than we
              would otherwise run it, for the obvious reason.</p>

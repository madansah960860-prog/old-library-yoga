            <blockquote class="quote">
              <p>I came at fourteen weeks because I was terrified and wanted
                something to do about it. What I actually got was six other
                people at roughly the same stage and a teacher who answered the
                question I asked rather than the one she wished I had asked. The
                yoga was good. The room was the thing.</p>
              <cite>Priya, came from 14 weeks, now has a two-year-old</cite>
            </blockquote>

            <blockquote class="quote">
              <p>I had a caesarean after a long labour and I felt, for months,
                like I had failed a test everybody else had passed. The first
                thing Anwen said to me when I came back was that a caesarean is
                a way of a baby being born and not a way of losing. I have
                thought about that sentence more often than I have thought about
                any of the exercises.</p>
              <cite>Hannah, postnatal class from 11 weeks</cite>
            </blockquote>

            <blockquote class="quote">
              <p>I had pelvic girdle pain from about twenty weeks and had been
                told by two different people to just rest. Anwen gave me a
                completely different version of every standing posture, told me
                to refer myself to a women's health physio, and wrote down the
                phrase to use when I rang. That referral is the reason I could
                still walk at thirty-six weeks.</p>
              <cite>Marta, prenatal and one-to-one</cite>
            </blockquote>

            <blockquote class="quote">
              <p>Friday's class is forty-five minutes of yoga and twenty minutes
                of tea, and I would have paid the same for the tea. My son
                screamed through most of the first four weeks and nobody once
                looked at me.</p>
              <cite>Sadie, mother and baby</cite>
            </blockquote>

            <blockquote class="quote">
              <p>I am not a yoga person. I did not become a yoga person. I did
                get an exhale I could actually use at four in the morning in a
                birth pool, and a shortlist of positions that meant my husband
                had something to do other than hover. That was worth the
                sixty-eight pounds on its own.</p>
              <cite>Eleri, prenatal from 26 weeks</cite>
            </blockquote>

            <blockquote class="quote">
              <p>I came back eighteen months after my daughter was born, which
                felt far too late to bother. It was not too late. Six weeks of
                dull breathing exercises fixed something I had assumed was
                permanent.</p>
              <cite>Joanne, postnatal</cite>
            </blockquote>

            <h2>About these</h2>
            <p>Every quotation on this page was written by the person named,
              sent to us by email, and published with their explicit permission.
              We have edited for length in three of them and for nothing else.
              First names are used because several people asked for that; two
              are used with a changed name at their request, which we have noted
              to them individually.</p>
            <p>Nobody received a free class, a discount or anything else in
              exchange. We do not run a review scheme, we have never asked
              anybody to post anything on a review site, and if we ever pay for
              or incentivise a testimonial it will say so on the page. That
              commitment is part of our
              <a href="../policies/editorial-policy.php">editorial policy</a>.</p>
            <p>We have also not filtered out the criticism. The things people
              most often say could be better are the stairs, the lack of an
              evening postnatal class, and the fact that the Saturday class
              books up two weeks ahead. All three are fair, and only the first
              is genuinely difficult to fix.</p>
          </div>

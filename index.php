            <h2>Practical things</h2>
          </div>
          <div class="prose">
            <h3>You do not need to be fit, flexible or experienced</h3>
            <p>Roughly two thirds of the people who come to Old Library Yoga had never
              done a yoga class before they were pregnant. Nothing in the
              prenatal class requires you to get down to the floor quickly, hold
              your own body weight, or know what any Sanskrit word means. There
              are chairs, and using one is not a lesser version of the
              class.</p>
            <h3>What to bring</h3>
            <p>Water, and layers &mdash; pregnancy makes most people run hot in
              the middle of a class and cold at the end of it. Everything else
              is here: mats, bolsters, blocks, straps, birth balls and a
              great many blankets. Wear whatever you can breathe and move in.</p>
            <h3>Cancelling</h3>
            <p>Tell us any time before the class starts and it is not charged.
              Not the evening before, not four hours before &mdash; any time.
              This is a client group that is regularly sick, exhausted, at a
              scan that overran, or simply unable to face leaving the house, and
              a cancellation policy that punishes that is a policy designed for
              a different business.</p>
            <h3>Prices</h3>
            <p>Drop-in &pound;15. Five-class card &pound;68, valid four months.
              Mother and baby &pound;11. Birth preparation workshop &pound;70
              for you and a partner together. One to one &pound;55.</p>
            <p>If money is the reason you are not coming, say so in an email.
              Two places in every class are free and there is no form.</p>

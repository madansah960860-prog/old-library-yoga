          <p>Old Library Yoga is a small studio that does one thing: yoga for people who
            are pregnant, and for people who have recently given birth. That
            narrowness is the point. A general class with a pregnancy
            modification offered from the front is not the same as a room where
            everybody is in the same situation, the props are already out, and
            nobody is going to suggest a jump-back.</p>
          <p>Classes are 75 minutes for prenatal, 60 for postnatal and 45 for
            mother and baby. You do not need to book a block, commit to a term,
            or arrive on a particular week of pregnancy. Most people come from
            around the end of the first trimester, but if you are twelve weeks
            and exhausted, or thirty-eight weeks and enormous, both are normal
            weeks to start.</p>
        </section>


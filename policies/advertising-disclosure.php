          <h1>Advertising disclosure</h1>
          <p class="lede">How Old Library Yoga makes money, who pays for it, and the line
            between the two. Short version: advertisers pay for space and have
            no say whatsoever in what we write.</p>
          <p><strong>Effective date:</strong> 2 February 2026.</p>

          <h2>Display advertising</h2>
          <p>This site carries third-party display advertising, served
            automatically by advertising networks including Google. Three
            positions are reserved on our pages &mdash; a leaderboard below the
            header, a rectangle within the body of longer pages, and a smaller
            rectangle near the foot. They are labelled
            &ldquo;Advertisement&rdquo; and they are laid out at a fixed size so
            that the page does not jump around while they load.</p>
          <p>We do not choose which advertisements appear. They are selected by
            the network, in real time, on the basis of the page&rsquo;s subject
            matter and &mdash; unless you have opted out &mdash; your previous
            browsing. This means we may be carrying an advertisement for a
            product we have never used, would not use, or actively disagree
            with. Seeing something advertised here is not a recommendation from
            us. If you see an advertisement that is offensive, misleading or
            obviously fraudulent, tell us at <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a>
            with the page address and we will block that advertiser.</p>
          <p>To control what data is used to select advertising, see our
            <a href="cookie-policy.php">cookie policy</a> and the opt-out
            routes listed in the <a href="privacy-policy.php">privacy
            policy</a>, including Google Ads Settings and optout.aboutads.info.</p>

          <h2>Affiliate links</h2>
          <p>There are no affiliate links anywhere on this site. We are asked constantly which pregnancy pillow and which birth ball to buy; the answer is given by email, names specific products, and earns us nothing from any of them. Where an affiliate link is used it is disclosed in plain
            English at the point of use, in the body of the page and not only in
            a footer. The price you pay is never higher for having used our
            link.</p>

          <h2>The wall between advertising and editorial</h2>
          <p>This is the part that actually matters, so we will be specific
            about the commitments rather than gesture at &ldquo;editorial
            independence&rdquo;.</p>
          <ul>
            <li>No advertiser, network or affiliate partner sees any article,
              page or recommendation before publication.</li>
            <li>No advertiser has ever been given, or will be given, the right
              to approve, veto, amend or delay anything we publish.</li>
            <li>We do not accept payment for a positive mention, a review, a
              ranking position, or an inclusion in any list. We do not sell
              &ldquo;guest posts&rdquo;, sponsored articles or link placements,
              and unsolicited offers to buy them are deleted unread.</li>
            <li>Nothing is recommended here because it pays better. Nothing here is recommended for money, and we have never been paid to mention a brand, a hospital, a birth centre or a private midwifery service.</li>
            <li>If a commercial relationship of any kind exists with someone or
              something we write about, that relationship is stated in the
              article itself.</li>
          </ul>

          <h2>Gifts, samples and hospitality</h2>
          <p>We accept no gifts, samples, free equipment or hospitality from brands in exchange for coverage. Pregnancy is a market that attracts a great deal of this and we have turned down all of it, including two offers of free birth balls for the studio. Anything we do accept is declared on the page it relates
            to, and accepting it never comes with an agreement about what we
            will say.</p>

          <h2>Why we carry advertising at all</h2>
          <p>Because the alternatives are worse. A paywall would put this
            material behind a card payment for people who mostly need one page
            of it. Sponsored content would compromise exactly the thing that
            makes the site worth reading. Advertising is imperfect, occasionally
            ugly, and honest about what it is: somebody is paying for space next
            to the words, and they are not paying for the words.</p>
          <p>If you would rather not see it, use an ad blocker. We will not
            block you, nag you, or hide the page behind a plea to turn it off.</p>

          <h2>Questions and complaints</h2>
          <p>Write to <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a>. If you think something
            on this site reads like an advertisement and is not labelled as one,
            say so &mdash; that is a serious complaint here and it will be
            treated as one.</p>


          <h1>Privacy policy</h1>
          <p class="lede">This policy explains what Old Library Yoga collects when you use
            https://www.oldlibraryyoga.co.uk, why we collect it, who else can see it, and exactly how to
            make us stop. It applies to this website only.</p>
          <p><strong>Effective date:</strong> 2 February 2026. <strong>Last
            reviewed:</strong> 2 February 2026.</p>

          <h2>Who we are</h2>
          <p>Old Library Yoga is operated by Old Library Yoga Ltd, whose registered address is:</p>
          <p>The Old Library<br>3 Wrenbury Street<br>Bristol<br>BS6 5QT<br>England</p>
          <p>For any question about this policy, about the data we hold, or to
            exercise any right described below, write to
            <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a>. A person reads that inbox. We aim
            to answer within five working days and are obliged to answer within
            one month.</p>

          <h2>What we collect</h2>
          <p><strong>Information you give us.</strong> If you email to book, we receive your name, your email address, the class you want, how many weeks pregnant you are or how long ago you gave birth, and anything you choose to tell us about your health. There is no booking account and no password. We only ask for
            what is needed to answer you, and we do not use it to build a
            marketing profile.</p>
          <p><strong>Log files.</strong> Like almost every website, our host
            records a standard server log each time a page is requested. A log
            line contains your IP address, the browser and operating system you
            used, the page you asked for, the page you came from if any, and the
            date and time. These logs are used to diagnose faults, to measure
            how heavily the site is being used, and to identify automated abuse.
            They are not linked to your name, and they are deleted on a rolling
            basis after 30 days.</p>
          <p><strong>Cookies and similar technologies.</strong> Cookies are
            small text files placed on your device. We set a small number
            ourselves and our advertising partners set others. The full
            breakdown, by category and purpose, is in our
            <a href="cookie-policy.php">cookie policy</a>.</p>
          <p>We do not knowingly collect special category data &mdash; health,
            biometrics, religion, ethnicity, political opinion, sexual
            orientation &mdash; and you should not send it to us in a contact
            form. Because this is a pregnancy and post-birth studio, people routinely tell us health information &mdash; a due date, a caesarean, pelvic girdle pain, a previous difficult birth. We need it to teach you safely. It is held in one mailbox read only by Anwen Pryce, it is never entered into any other system, it is never shared with anyone, and it is deleted the moment you ask or when you stop attending.</p>

          <h2>Third-party vendors and advertising</h2>
          <p>This site carries third-party display advertising. Third-party
            vendors, including Google, use cookies to serve advertisements based
            on your prior visits to this website and to other websites.</p>
          <p><strong>Google&rsquo;s DoubleClick DART cookie.</strong> Google is
            a third-party vendor on this site. Google uses the DoubleClick DART
            cookie to serve advertisements to visitors of https://www.oldlibraryyoga.co.uk based on their
            visit to our site and other sites on the internet. You may opt out
            of the DART cookie by visiting the Google advertising and content
            network privacy policy at
            <a href="https://policies.google.com/technologies/ads" rel="nofollow noopener"
               target="_blank">policies.google.com/technologies/ads</a>.</p>
          <p><strong>Turning personalised advertising off.</strong> You have
            three independent routes, and any one of them works on its own:</p>
          <ul>
            <li>Google Ads Settings at
              <a href="https://adssettings.google.com" rel="nofollow noopener"
                 target="_blank">adssettings.google.com</a> &mdash; switch off ad
              personalisation across Google&rsquo;s own services and partner
              sites.</li>
            <li>The Digital Advertising Alliance opt-out at
              <a href="https://optout.aboutads.info" rel="nofollow noopener"
                 target="_blank">optout.aboutads.info</a>, and the European
              equivalent at
              <a href="https://www.youronlinechoices.eu" rel="nofollow noopener"
                 target="_blank">youronlinechoices.eu</a>.</li>
            <li>Your browser&rsquo;s own cookie controls, which are described
              step by step in our <a href="cookie-policy.php">cookie
              policy</a>.</li>
          </ul>
          <p>Switching personalisation off does not remove advertising from this
            site. It means the advertising you see stops being selected on the
            basis of your browsing history and becomes contextual instead. We
            have no access to, and no control over, the cookies that third-party
            advertisers set; each vendor acts as its own data controller and
            under its own policy.</p>

          <h2>Legal basis for processing</h2>
          <p>Where the UK GDPR and EU GDPR apply, we rely on: <em>consent</em>
            for advertising and analytics cookies, which you give or withhold in
            the cookie banner and can change at any time; <em>legitimate
            interests</em> for server logs and security monitoring, because a
            site that cannot be kept running and free of abuse cannot be offered
            at all; and <em>contract</em> where you have asked us for something
            specific that requires a reply.</p>

          <h2>Your rights under GDPR</h2>
          <p>If you are in the United Kingdom or the European Economic Area you
            have the right to: be told what personal data we hold about you and
            receive a copy of it; have inaccurate data corrected; have data
            erased; restrict or object to processing, including a standalone
            right to object to direct marketing at any time; receive your data
            in a portable, machine-readable format; and withdraw consent at any
            time without that affecting processing already carried out.</p>
          <p>To use any of these rights, email <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a>.
            We will not charge you and we will not ask why. If you are
            dissatisfied with our response you may complain to the Information
            Commissioner&rsquo;s Office at ico.org.uk, or to your own national
            supervisory authority.</p>

          <h2>Your rights under the CCPA/CPRA</h2>
          <p>If you are a California resident you have the right to know the
            categories of personal information collected, the categories of
            sources, the business purpose, and the categories of third parties
            with whom it is shared; the right to request deletion; the right to
            correct inaccurate information; the right to opt out of the
            &ldquo;sale&rdquo; or &ldquo;sharing&rdquo; of personal information,
            which under California law includes some advertising cookie
            activity; and the right not to be discriminated against for
            exercising any of these rights.</p>
          <p>We do not sell personal information for money. To opt out of
            advertising-related sharing, use the cookie banner or the vendor
            opt-outs listed above, or email us with the subject line &ldquo;Do
            Not Sell or Share My Personal Information&rdquo;. We will confirm
            within ten business days and act within forty-five.</p>

          <h2>Children</h2>
          <p>This site is intended for adults. In line with the Children&rsquo;s
            Online Privacy Protection Act (COPPA), we do not knowingly collect
            personal information from children under 13, and we do not direct
            any part of this site or its advertising to children. Babies attend the Friday class with a parent or carer, and we hold no data about them at all &mdash; not a name, not a date of birth. We do not photograph babies or children for this site, and no image on it shows one. If
            you believe a child has provided us with personal information,
            contact <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a> and we will delete it
            promptly.</p>

          <h2>Retention, security and transfers</h2>
          <p>Server logs are kept 30 days. Correspondence is kept for two years
            from our last exchange, then deleted. The site is served over HTTPS
            and access to the inbox is limited to named people. Some of our
            vendors, including Google, process data outside the UK and EEA; they
            do so under standard contractual clauses or an equivalent approved
            transfer mechanism.</p>

          <h2>Changes to this policy</h2>
          <p>If we change this policy we will change the effective date at the
            top and, for any material change, place a notice on the site for
            thirty days. Continued use after that constitutes acceptance.</p>


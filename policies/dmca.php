          <h1>DMCA notice and takedown</h1>
          <p class="lede">Old Library Yoga Ltd respects copyright. If material on https://www.oldlibraryyoga.co.uk
            infringes yours, this page tells you exactly how to have it removed,
            and how to contest a removal you believe was wrong.</p>
          <p><strong>Effective date:</strong> 2 February 2026.</p>

          <h2>Our position</h2>
          <p>Everything published on this site is written in-house or licensed.
            Photographs come from free-licence libraries and each one is listed,
            with its source and photographer, in the CREDITS file inside the
            site&rsquo;s image folder. We do not republish other people&rsquo;s
            articles, and we do not copy class descriptions, safety guidance or articles from other publishers.</p>
          <p>Mistakes are still possible &mdash; a mis-attributed photograph, a
            quotation longer than fair dealing allows, an image whose licence
            turns out to have been misrepresented upstream. When that happens we
            want to fix it quickly, and we would always rather correct or credit
            than argue.</p>

          <h2>How to send a notice</h2>
          <p>Send your notice by email to <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a> with
            the subject line <strong>DMCA Notice</strong>, or by post to the
            designated agent below. Under 17 U.S.C. &sect; 512(c)(3), a valid
            notice must include all six of the following:</p>
          <ol>
            <li>A physical or electronic signature of the copyright owner, or of
              a person authorised to act on their behalf.</li>
            <li>Identification of the copyrighted work claimed to have been
              infringed. If several works are covered by one notice, a
              representative list of them.</li>
            <li>Identification of the material that is claimed to be infringing,
              with enough detail for us to locate it &mdash; in practice, the
              full URL of the page and a description of the specific image,
              paragraph or file.</li>
            <li>Your contact details: full name, postal address, telephone
              number and email address.</li>
            <li>A statement that you have a good-faith belief that the disputed
              use is not authorised by the copyright owner, its agent, or the
              law.</li>
            <li>A statement that the information in the notice is accurate and,
              under penalty of perjury, that you are the copyright owner or
              authorised to act on the owner&rsquo;s behalf.</li>
          </ol>
          <p>Please note that under 17 U.S.C. &sect; 512(f) a person who
            knowingly materially misrepresents that material is infringing may
            be liable for damages, including costs and legal fees.</p>

          <h2>What we do when we receive one</h2>
          <p>We acknowledge receipt within two working days. We remove or
            disable access to the material identified, usually within five
            working days and often the same day. We keep a record of the notice
            and of the action taken. Where the material was supplied by a
            contributor, we notify them and pass on a copy of the notice.</p>
          <p>We operate a repeat-infringer policy: any contributor who is the
            subject of repeated valid notices stops contributing to this
            site.</p>

          <h2>Counter-notice</h2>
          <p>If your material was removed and you believe that was a mistake or
            a misidentification, you may send a counter-notice to the same
            address with the subject line <strong>DMCA Counter-Notice</strong>.
            Under 17 U.S.C. &sect; 512(g)(3) it must contain:</p>
          <ol>
            <li>Your physical or electronic signature.</li>
            <li>Identification of the material removed and the location at which
              it appeared before removal.</li>
            <li>A statement under penalty of perjury that you have a good-faith
              belief the material was removed as a result of mistake or
              misidentification.</li>
            <li>Your name, postal address and telephone number, and a statement
              that you consent to the jurisdiction of the Federal District Court
              for the judicial district in which your address is located, or, if
              your address is outside the United States, to the jurisdiction of
              any judicial district in which we may be found; and that you will
              accept service of process from the person who gave the original
              notice or their agent.</li>
          </ol>
          <p>We forward a valid counter-notice to the original complainant. If
            they do not tell us within ten to fourteen business days that they
            have filed an action seeking a court order, we may restore the
            material.</p>

          <h2>Designated agent</h2>
          <p>Copyright Agent, Old Library Yoga Ltd<br>The Old Library<br>3 Wrenbury Street<br>Bristol<br>BS6 5QT<br>England<br>
            <a href="mailto:hello@oldlibraryyoga.co.uk">hello@oldlibraryyoga.co.uk</a></p>
          <p>If you are outside the United States, or your complaint is better
            handled under UK or EU copyright law, send it to the same address.
            We apply the same process regardless of which statute you rely on,
            and you do not need to cite the DMCA for us to act.</p>

          <h2>A quicker alternative</h2>
          <p>If your concern is attribution rather than removal &mdash; you are
            the photographer and simply want to be credited, or credited
            differently &mdash; say so in a plain email. That is usually fixed
            the same day and does not need a formal notice.</p>

